const loaded = new Set<string>();
/** Loads a name font the first time something shows it. */
export function loadNameFont(id: string | null | undefined): void {
  if (!id || loaded.has(id) || !LOADERS[id]) return;
  loaded.add(id);
  void LOADERS[id]!().catch(() => loaded.delete(id));
}

const FAMILY = new Map(NAME_FONTS.map((f) => [f.id, f.family]));
export const nameFontFamily = (id: string | null | undefined) => (id ? FAMILY.get(id) : undefined);
